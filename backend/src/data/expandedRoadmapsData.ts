import type { RoadmapSeedItem } from './roadmapsData';

let stepCounter = 301;
const nextStepId = (): string => {
  const num = stepCounter++;
  return `d2000000-0000-0000-0000-${String(num).padStart(12, '0')}`;
};

interface StageDraft {
  step_number: number;
  title: string;
  title_hi: string;
  title_te: string;
  description: string;
  description_hi: string;
  description_te: string;
  learning_objectives: string[];
  estimated_duration: string;
  resource_links: Array<{ title: string; url: string; provider: string; is_free: boolean }>;
  action_cta: string;
  schemes_applicable: string[];
}

function buildRoadmap(
  suffix: string,
  title: string,
  estimated_duration: string,
  stages: StageDraft[]
): RoadmapSeedItem {
  return {
    id: `d1000000-0000-0000-0000-0000000000${suffix}`,
    career_id: `a1000000-0000-0000-0000-0000000000${suffix}`,
    title,
    total_stages: stages.length,
    estimated_duration,
    steps: stages.map((st) => ({
      id: nextStepId(),
      ...st,
    })),
  };
}

